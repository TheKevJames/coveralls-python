import importlib.metadata
import logging
import sys
from typing import Annotated
from typing import Any

import typer

from .api import Coveralls


log = logging.getLogger('coveralls')
APP_HELP = """Publish coverage results online via coveralls.io.

This tool makes custom reports for data generated by coverage.py package and
sends it to the coveralls.io service API.

All Python files in your coverage analysis are posted to this service along
with coverage stats, so please make sure you're not ruining your own security!

Usage patterns:
  coveralls [OPTIONS]
  coveralls debug [OPTIONS]

Example:
  $ coveralls
  Submitting coverage to coveralls.io...
  Coverage submitted!
"""
DEBUG_HELP = (
    "Don't send anything, just output json to stdout. Also forces verbose "
    'output. Please use debug mode when submitting bug reports.'
)


app = typer.Typer(
    add_completion=True,
    context_settings={'help_option_names': ['-h', '--help']},
    help=APP_HELP,
)


def _show_version(value: bool) -> None:
    if value:
        typer.echo(importlib.metadata.version('coveralls'))
        raise typer.Exit()


def _resolve_deprecated(
    new: str | None, old: str | None,
    new_flag: str, old_flag: str,
) -> str | None:
    """Prefer the canonical value, warning when the deprecated flag is used."""
    if old is None:
        return new
    log.warning(
        '%s is deprecated and will be removed in a future release; use %s '
        'instead.', old_flag, new_flag,
    )
    return new if new is not None else old


def _run(
    *,
    is_debug: bool,
    service_name: str | None,
    rcfile: str | None,
    base_dir: str | None,
    src_dir: str | None,
    output: str | None,
    submit: str | None,
    merge: str | None,
    finish: bool,
    parallel: bool | None,
    host: str | None,
    skip_ssl_verify: bool | None,
    verbose: bool,
    timeout: float | None,
    connect_timeout: float | None,
    read_timeout: float | None,
) -> None:
    # pylint: disable=too-complex,too-many-locals,too-many-arguments
    if is_debug:
        verbose = True

    level = logging.DEBUG if verbose else logging.INFO
    log.addHandler(logging.StreamHandler())
    log.setLevel(level)

    token_required = not is_debug and not output

    # Forward every CLI value as-is and let resolve() own precedence: it drops
    # the ones left unset (None) so a flag that was not passed cannot clobber a
    # value from the environment or config file. Passing an explicit value
    # (including a False from --no-parallel/--no-skip-ssl-verify) overrides,
    # keeping the CLI and library entrypoints on identical precedence rules.
    overrides: dict[str, Any] = {
        'rcfile': rcfile,
        'service_name': service_name,
        'base_dir': base_dir,
        'src_dir': src_dir,
        'host': host,
        'parallel': parallel,
        'skip_ssl_verify': skip_ssl_verify,
        'timeout': timeout,
        'connect_timeout': connect_timeout,
        'read_timeout': read_timeout,
    }

    try:
        coverallz = Coveralls(token_required, **overrides)

        if merge:
            coverallz.merge(merge)

        if is_debug:
            log.info('Testing coveralls-python...')
            coverallz.wear(dry_run=True)
            return

        if output:
            log.info('Write coverage report to file...')
            coverallz.save_report(output)
            return

        if submit:
            with open(submit) as report_file:
                coverallz.submit_report(report_file.read())
            return

        if finish:
            log.info('Finishing parallel jobs...')
            coverallz.parallel_finish()
            log.info('Done')
            return

        log.info('Submitting coverage to coveralls.io...')
        result = coverallz.wear()

        log.info('Coverage submitted!')
        log.debug(result)
        if result:
            log.info(result.get('message'))
            log.info(result.get('url'))
    except KeyboardInterrupt:  # pragma: no cover
        log.info('Aborted')
    except Exception as e:
        log.exception('Error running coveralls: %s', e)
        sys.exit(1)


# Shared option specs, defined once and referenced by both the default command
# and the ``debug`` subcommand so the two entry points cannot drift apart.
_ServiceName = Annotated[
    str | None,
    typer.Option(
        '--service-name',
        help='Provide an alternative service name to submit.',
    ),
]
_Service = Annotated[
    str | None,
    typer.Option(
        '--service', hidden=True, help='Deprecated alias for --service-name.',
    ),
]
_Rcfile = Annotated[
    str | None,
    typer.Option(
        '--rcfile',
        help='Specify the coverage.py config file (default: auto-discovered).',
    ),
]
_BaseDir = Annotated[
    str | None,
    typer.Option(
        '--base-dir',
        help='Base directory that is removed from reported paths.',
    ),
]
_Basedir = Annotated[
    str | None,
    typer.Option(
        '--basedir', hidden=True, help='Deprecated alias for --base-dir.',
    ),
]
_SrcDir = Annotated[
    str | None,
    typer.Option(
        '--src-dir', help='Source directory added to reported paths.',
    ),
]
_Srcdir = Annotated[
    str | None,
    typer.Option(
        '--srcdir', hidden=True, help='Deprecated alias for --src-dir.',
    ),
]
_Output = Annotated[
    str | None,
    typer.Option(
        '--output', help="Write report to file. Doesn't send "
        'anything.',
    ),
]
_Submit = Annotated[
    str | None,
    typer.Option('--submit', help='Upload a previously generated file.'),
]
_Merge = Annotated[
    str | None,
    typer.Option('--merge', help='Merge report from file when submitting.'),
]
_Finish = Annotated[
    bool,
    typer.Option('--finish', help='Finish parallel jobs.'),
]
_Parallel = Annotated[
    bool | None,
    typer.Option(
        '--parallel/--no-parallel',
        help='Submit as one of several parallel jobs to be merged.',
    ),
]
_Host = Annotated[
    str | None,
    typer.Option('--host', help='Coveralls API host base URL.'),
]
_SkipSslVerify = Annotated[
    bool | None,
    typer.Option(
        '--skip-ssl-verify/--no-skip-ssl-verify',
        help='Skip verification of the SSL certificate of the host.',
    ),
]
_Verbose = Annotated[
    bool,
    typer.Option(
        '-v', '--verbose',
        help='Print extra info, always enabled when debugging.',
    ),
]
_Timeout = Annotated[
    float | None,
    typer.Option(
        '--timeout',
        help='Connect and read timeout, in seconds (default: 10/60).',
    ),
]
_ConnectTimeout = Annotated[
    float | None,
    typer.Option(
        '--connect-timeout', help='Connect timeout, in seconds (default: 10).',
    ),
]
_ReadTimeout = Annotated[
    float | None,
    typer.Option(
        '--read-timeout', help='Read timeout, in seconds (default: 60).',
    ),
]
_Version = Annotated[
    bool | None,
    typer.Option(
        '--version', callback=_show_version, is_eager=True,
        help='Display the version and exit.',
    ),
]


def _dispatch(
    *,
    is_debug: bool,
    service_name: str | None,
    service: str | None,
    rcfile: str | None,
    base_dir: str | None,
    basedir: str | None,
    src_dir: str | None,
    srcdir: str | None,
    output: str | None,
    submit: str | None,
    merge: str | None,
    finish: bool,
    parallel: bool | None,
    host: str | None,
    skip_ssl_verify: bool | None,
    verbose: bool,
    timeout: float | None,
    connect_timeout: float | None,
    read_timeout: float | None,
) -> None:
    # pylint: disable=too-many-arguments,too-many-locals
    service_name = _resolve_deprecated(
        service_name, service, '--service-name', '--service',
    )
    base_dir = _resolve_deprecated(
        base_dir, basedir, '--base-dir', '--basedir',
    )
    src_dir = _resolve_deprecated(src_dir, srcdir, '--src-dir', '--srcdir')

    _run(
        is_debug=is_debug,
        service_name=service_name,
        rcfile=rcfile,
        base_dir=base_dir,
        src_dir=src_dir,
        output=output,
        submit=submit,
        merge=merge,
        finish=finish,
        parallel=parallel,
        host=host,
        skip_ssl_verify=skip_ssl_verify,
        verbose=verbose,
        timeout=timeout,
        connect_timeout=connect_timeout,
        read_timeout=read_timeout,
    )


@app.callback(invoke_without_command=True)
def coveralls(
    ctx: typer.Context,
    service_name: _ServiceName = None,
    service: _Service = None,
    rcfile: _Rcfile = None,
    base_dir: _BaseDir = None,
    basedir: _Basedir = None,
    src_dir: _SrcDir = None,
    srcdir: _Srcdir = None,
    output: _Output = None,
    submit: _Submit = None,
    merge: _Merge = None,
    finish: _Finish = False,
    parallel: _Parallel = None,
    host: _Host = None,
    skip_ssl_verify: _SkipSslVerify = None,
    verbose: _Verbose = False,
    timeout: _Timeout = None,
    connect_timeout: _ConnectTimeout = None,
    read_timeout: _ReadTimeout = None,
    version: _Version = None,
) -> None:
    # pylint: disable=too-many-arguments,too-many-positional-arguments
    # pylint: disable=too-many-locals
    if ctx.invoked_subcommand is not None:
        return
    _ = version
    _dispatch(
        is_debug=False,
        service_name=service_name,
        service=service,
        rcfile=rcfile,
        base_dir=base_dir,
        basedir=basedir,
        src_dir=src_dir,
        srcdir=srcdir,
        output=output,
        submit=submit,
        merge=merge,
        finish=finish,
        parallel=parallel,
        host=host,
        skip_ssl_verify=skip_ssl_verify,
        verbose=verbose,
        timeout=timeout,
        connect_timeout=connect_timeout,
        read_timeout=read_timeout,
    )


