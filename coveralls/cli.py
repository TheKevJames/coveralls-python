log = logging.getLogger('coveralls')
# One template for every "X is deprecated, use Y" warning so the deprecated
# option aliases and the deprecated verb flags cannot drift apart.
DEPRECATION_TEMPLATE = (
    '%s is deprecated and will be removed in a future release; use %s instead.'
)
APP_HELP = """Publish coverage results online via coveralls.io.

This tool makes custom reports for data generated by coverage.py package and
sends it to the coveralls.io service API.

All Python files in your coverage analysis are posted to this service along
with coverage stats, so please make sure you're not ruining your own security!

Run without a command to collect and submit coverage; see commands below.
"""
DEBUG_HELP = (
    "Don't send anything, just output json to stdout. Also forces verbose "
    'output. Please use debug mode when submitting bug reports.'
)


app = typer.Typer(
    add_completion=True,
    context_settings={'help_option_names': ['-h', '--help']},
    help=APP_HELP,
)


def _show_version(value: bool) -> None:
    if value:
        typer.echo(importlib.metadata.version('coveralls'))
        raise typer.Exit()


def _configure_logging(*, verbose: bool) -> None:
    # Guard against duplicate handlers: main() may be invoked more than once in
    # the same process (tests, library reuse) and each StreamHandler would
    # otherwise stack up and multiply the output.
    if not log.handlers:
        log.addHandler(logging.StreamHandler())
    log.setLevel(logging.DEBUG if verbose else logging.INFO)


def _resolve_deprecated(
    new: str | None, old: str | None,
    new_flag: str, old_flag: str,
) -> str | None:
    """Prefer the canonical value, warning when the deprecated flag is used."""
    if old is None:
        return new
    log.warning(DEPRECATION_TEMPLATE, old_flag, new_flag)
    return new if new is not None else old


def _warn_deprecated_verb(old_flag: str, new_command: str) -> None:
    """Warn that an action flag is superseded by a subcommand."""
    log.warning(DEPRECATION_TEMPLATE, old_flag, new_command)


def _make_coveralls(
    *, token_required: bool,
    service_name: str | None = None, service: str | None = None,
    rcfile: str | None = None,
    base_dir: str | None = None, basedir: str | None = None,
    src_dir: str | None = None, srcdir: str | None = None,
    host: str | None = None, skip_ssl_verify: bool | None = None,
    parallel: bool | None = None,
    carryforward: str | None = None,
    timeout: float | None = None,
    connect_timeout: float | None = None, read_timeout: float | None = None,
    retries: int | None = None,
) -> Coveralls:
    # pylint: disable=too-many-arguments,too-many-locals
    # Modifiers not exposed by a command default to None; resolve() drops unset
    # ones so nothing clobbers env/config. An explicit value (incl. a False
    # from --no-parallel) overrides.
    service_name = _resolve_deprecated(
        service_name, service, '--service-name', '--service',
    )
    base_dir = _resolve_deprecated(
        base_dir, basedir, '--base-dir', '--basedir',
    )
    src_dir = _resolve_deprecated(src_dir, srcdir, '--src-dir', '--srcdir')

    overrides: dict[str, Any] = {
        'rcfile': rcfile,
        'service_name': service_name,
        'base_dir': base_dir,
        'src_dir': src_dir,
        'host': host,
        'parallel': parallel,
        'carryforward': carryforward,
        'skip_ssl_verify': skip_ssl_verify,
        'timeout': timeout,
        'connect_timeout': connect_timeout,
        'read_timeout': read_timeout,
        'retries': retries,
    }
    return Coveralls(token_required, **overrides)


def _action_submit(coverallz: Coveralls, merge: str | None) -> None:
    if merge:
        coverallz.merge(merge)
    log.info('Submitting coverage to coveralls.io...')
    result = coverallz.wear()
    log.info('Coverage submitted!')
    log.debug(result)
    if result:
        log.info(result.get('message'))
        log.info(result.get('url'))


def _action_save(coverallz: Coveralls, merge: str | None, path: str) -> None:
    if merge:
        coverallz.merge(merge)
    log.info('Write coverage report to file...')
    coverallz.save_report(path)


# merge is a no-op for upload/finish (their payloads ignore the merged data),
# but the old flat CLI ran it before every action, so the deprecated
# --submit/--finish paths pass it for identical dispatch.
def _action_upload(
    coverallz: Coveralls, path: str, merge: str | None = None,
) -> None:
    if merge:
        coverallz.merge(merge)
    report = pathlib.Path(path).read_text(encoding='utf-8')
    coverallz.submit_report(report)


def _action_finish(coverallz: Coveralls, merge: str | None = None) -> None:
    if merge:
        coverallz.merge(merge)
    log.info('Finishing parallel jobs...')
    coverallz.parallel_finish()
    log.info('Done')


def _action_debug(coverallz: Coveralls, merge: str | None) -> None:
    if merge:
        coverallz.merge(merge)
    log.info('Testing coveralls-python...')
    coverallz.wear(dry_run=True)


